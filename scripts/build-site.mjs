/* ── machine-readable indexes ────────────────────────────────────────────────────── */

/** sitemaps.org 0.9, <loc> only. Google ignores <priority> and <changefreq>, and reads
 *  <lastmod> only where it is consistently accurate — nothing here knows when a page last
 *  changed in a way a reader would care about, so no date is claimed. */
const sitemapXml = urls =>
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map(url => `  <url>\n    <loc>${escape(url)}</loc>\n  </url>\n`).join('') +
  '</urlset>\n'

/** llmstxt.org: an H1, a blockquote summary, then one H2 section per plugin listing that
 *  plugin's page and each of its skills. Every value is read from the catalog, a
 *  plugin.json, or a SKILL.md frontmatter — nothing here is written by hand. */
const llmsTxt = ({ catalog, plugins, mcpPage, siteUrl, repoUrl }) => {
  const sections = plugins.map(plugin => {
    const rows = [
      `- [${plugin.name}@${catalog.name}](${siteUrl}${plugin.name}/): ${shortNote(plugin.description)}`,
      ...plugin.skills.map(
        skill =>
          `- [${skill.name}](${repoUrl}/blob/main/${plugin.source}/skills/${skill.name}/SKILL.md): ` +
          shortNote(skill.description)
      )
    ]
    return `## ${plugin.display}\n\n${rows.join('\n')}\n`
  })

  const mcpSection =
    `## ${mcpPage.label}\n\n` +
    `- [${mcpPage.label}](${mcpPage.url}): ${shortNote(mcpPage.description)}\n`

  return (
    `# ${catalog.name}\n\n> ${catalog.description}\n\n` + `${sections.join('\n')}\n${mcpSection}`
  )
}

/** A sub-page's visible breadcrumb, in schema.org form: the same two labels and the same
 *  destination, so the markup stays a true representation of what the page shows. The last
 *  item is the page itself and so carries no `item` URL. */
const breadcrumbJsonLd = (catalog, pageLabel, siteUrl) =>
  JSON.stringify(
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: catalog.name, item: siteUrl },
        { '@type': 'ListItem', position: 2, name: pageLabel }
      ]
    },
    null,
    2
    // Inside a <script> element an entity is not decoded, so only `<` needs neutralising.
  ).replaceAll('<', '\\u003c')

/* ── rendering ───────────────────────────────────────────────────────────────────── */

const loadPartials = async () => {
  const files = (await readdir(PARTIALS)).filter(file => file.endsWith('.html'))
  const entries = await Promise.all(
    files.map(async file => [basename(file, '.html'), await readFile(join(PARTIALS, file), 'utf8')])
  )
  return Object.fromEntries(entries)
}

const render = (template, partials, tokens, label) => {
  const withPartials = template.replace(/\{\{>([a-z-]+)\}\}/g, (match, name) => {
    if (!(name in partials)) {
      throw new Error(`${label}: no partial named '${name}' in site/partials/`)
    }
    return partials[name]
  })

  // A function replacement, because a string one would read $&, $', $` and $$ inside the
  // value as substitution patterns — and escape() puts a & in front of every quote.
  const html = Object.entries(tokens).reduce(
    (page, [token, value]) => page.replaceAll(`{{${token}}}`, () => value),
    withPartials
  )

  const unresolved = html.match(/\{\{[A-Z_]+\}\}/g)
  if (unresolved) {
    throw new Error(`${label}: token(s) with no value: ${[...new Set(unresolved)].join(', ')}`)
  }
  return html
}

/** `relativePath` is POSIX-style, because it addresses a URL as much as a file. */
const writeOutput = async (relativePath, contents) => {
  const path = join(OUT, ...relativePath.split('/'))
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, contents)
}

/** Writes one page and returns its absolute URL. sitemap.xml is built from what these
 *  return, so it lists exactly the pages this build wrote. */
const writePage = async (relativePath, html, siteUrl) => {
  await writeOutput(relativePath, html)
  return `${siteUrl}${relativePath.replace(/(^|\/)index\.html$/, '$1')}`
}

/** Refuses any path containing the repository. `relative`, unlike an OUT + separator
 *  prefix, also handles the filesystem root without turning `/` into `//`. */
const assertOutputOutsideRepository = () => {
  const rootFromOutput = relative(OUT, ROOT)
  const outputContainsRoot =
    rootFromOutput === '' ||
    (rootFromOutput !== '..' && !rootFromOutput.startsWith(`..${sep}`) && !isAbsolute(rootFromOutput))

  if (outputContainsRoot) {
    throw new Error(`refusing to empty ${OUT}: it contains the repository`)
  }
}

/** Removes an empty directory or an output carrying this generator's exact ownership
 *  marker. An index.html is not proof of ownership: it may be somebody else's site. */
const cleanOutputDir = async () => {
  assertOutputOutsideRepository()
  if (!existsSync(OUT)) return false

  const entries = await readdir(OUT)
  if (entries.length > 0) {
    let marker = ''
    try {
      marker = await readFile(join(OUT, BUILD_MARKER), 'utf8')
    } catch {
      // The single refusal below gives the caller the path and recovery action.
    }
    if (marker !== BUILD_MARKER_CONTENT) {
      throw new Error(
        `refusing to empty ${OUT}: it holds files that are not a previous build ` +
          `(missing or invalid ${BUILD_MARKER}). Pass an empty directory, or delete it yourself.`
      )
    }
  }

  await rm(OUT, { recursive: true, force: true })
  return true
}

/** Empties only a marked previous build so deleted plugins and skills leave no stale page. */
const resetOutputDir = async () => {
  await cleanOutputDir()
  await mkdir(OUT, { recursive: true })
  await writeFile(join(OUT, BUILD_MARKER), BUILD_MARKER_CONTENT)
}

/** Every file in site/ that is not one of the templates below is copied out as it is. */
const TEMPLATES = new Set(['template.html', 'plugin.html', 'mcp.html'])

const copyAssets = async () => {
  const assets = (await readdir(SITE, { withFileTypes: true }))
    .filter(entry => entry.isFile() && !TEMPLATES.has(entry.name))
    .map(entry => entry.name)
  await Promise.all(assets.map(file => copyFile(join(SITE, file), join(OUT, file))))
  return assets
}

const build = async () => {
  const catalog = await readJson(join(ROOT, '.claude-plugin', 'marketplace.json'))
  const entries = catalog.plugins.filter(entry => typeof entry.source === 'string')
  if (entries.length === 0) {
    throw new Error('the catalog lists no plugin with a local source path')
  }

  const plugins = await Promise.all(entries.map(readPlugin))
  const skillCount = plugins.reduce((total, plugin) => total + plugin.skills.length, 0)
  if (skillCount === 0) {
    throw new Error('no SKILL.md found under any catalogued plugin')
  }

  // A plugin page renders to /<plugin>/ and the MCP page to /<MCP_PAGE_DIR>/, so one name
  // addresses both. Refuse rather than let whichever is written second win silently.
  const collision = plugins.find(plugin => plugin.name === MCP_PAGE_DIR)
  if (collision) {
    throw new Error(
      `plugin '${collision.name}' would render to ${MCP_PAGE_DIR}/, where the MCP page is ` +
        'written. Rename the plugin, or move the MCP page by changing MCP_PAGE_DIR.'
    )
  }

  // Whichever plugin owns an MCP server is the one the MCP section documents. A plugin
  // that owns none needs no setup, so it is never the subject there.
  const mcpOwner = plugins.find(plugin => plugin.servers.length > 0) ?? plugins[0]
  const mcpServer = mcpOwner.servers[0]

  // Skills that need the server, taken from the same fact the plugin pages' "Requires" row
  // reads — the skill's plugin declares it — rather than from a list written by hand.
  const mcpSkills = plugins.flatMap(plugin =>
    plugin.servers.some(server => server.name === mcpServer?.name)
      ? plugin.skills.map(skill => ({ skill, plugin }))
      : []
  )

  const repoUrl = (entries[0].repository ?? `${catalog.owner.url}/${catalog.name}`).replace(/\.git$/, '')
  const [owner, repo] = repoUrl.split('/').slice(-2)
  const siteUrl = `https://${owner.toLowerCase()}.github.io/${repo}/`
  const catalogSentence = escape(catalog.description.replace(/\.?$/, '.'))

  // Tokens every page shares. Page-specific ones are merged in below.
  const common = {
    CATALOG_NAME: escape(catalog.name),
    SITE_URL: siteUrl,
    CATALOG_DESCRIPTION: escape(catalog.description),
    REPO_URL: repoUrl,
    REPO_SLUG: `${owner}/${repo}`,
    REPO_NAME: repo,
    INSTALL_URL: `https://raw.githubusercontent.com/${owner}/${repo}/main/install.sh`,
    PLUGIN_VERSIONS: plugins
      .map(plugin => `${escape(plugin.name)} v${escape(plugin.version)}`)
      .join(' · ')
  }

  // Everything the MCP server declares about itself, shared by the catalog page's setup
  // section and by the page devoted to the server, so the two cannot describe it differently.
  const mcpTokens = {
    MCP_PAGE_PATH: MCP_PAGE_DIR,
    MCP_PLUGIN: escape(mcpOwner.name),
    MCP_SOURCE: escape(mcpOwner.source),
    MCP_SERVER: escape(mcpServer?.name ?? ''),
    MCP_URL: escape(mcpServer?.url ?? ''),
    MCP_HEADER: escape(Object.keys(mcpServer?.headers ?? {})[0] ?? ''),
    MCP_TRANSPORT: escape(mcpServer?.type ?? ''),
    MCP_TRANSPORT_LABEL: escape(TRANSPORTS[mcpServer?.type] ?? mcpServer?.type ?? ''),
    MCP_CREDENTIAL_TITLE: escape(mcpServer?.credentialTitle ?? 'MCP credential')
  }

  await resetOutputDir()

  const partials = await loadPartials()

  const indexHtml = render(
    await readFile(join(SITE, 'template.html'), 'utf8'),
    partials,
    {
      ...common,
      ...mcpTokens,
      ROOT: './',
      PAGE_TITLE: `${escape(catalog.name)} — ${SITE_IDENTITY}`,
      PAGE_DESCRIPTION: `${catalogSentence} Install the skills into Claude Code, the skills CLI, or any agent that reads SKILL.md.`,
      PAGE_URL: siteUrl,
      CATALOG_SENTENCE: catalogSentence,
      PLUGIN_COUNT_PHRASE: plural(plugins.length, 'plugin'),
      SKILL_COUNT_PHRASE: plural(skillCount, 'skill'),
      PLUGIN_INSTALL_LINES: plugins
        .map(plugin => `/plugin install ${escape(plugin.name)}@${escape(catalog.name)}`)
        .join('\n'),
      PLUGIN_CARDS: plugins.map(plugin => pluginCard(plugin, './')).join('\n')
    },
    'site/template.html'
  )
  const indexUrl = await writePage('index.html', indexHtml, siteUrl)

  const pluginTemplate = await readFile(join(SITE, 'plugin.html'), 'utf8')
  const pluginUrls = await Promise.all(
    plugins.map(plugin => {
      const html = render(
        pluginTemplate,
        partials,
        {
          ...common,
          ROOT: '../',
          // The plugin's own name, then what the site is. `<plugin> — <catalog>` spent the
          // strongest title signal a result has on a name the reader cannot place yet.
          PAGE_TITLE: `${escape(plugin.display)} — ${SITE_IDENTITY}`,
          PAGE_DESCRIPTION: escape(plugin.description.replace(/\.?$/, '.')),
          PAGE_URL: `${siteUrl}${plugin.name}/`,
          PLUGIN_NAME: escape(plugin.name),
          PLUGIN_DISPLAY: escape(plugin.display),
          PLUGIN_DESCRIPTION: escape(plugin.description),
          PLUGIN_VERSION: escape(plugin.version),
          PLUGIN_REF: `${escape(plugin.name)}@${escape(catalog.name)}`,
          PLUGIN_SOURCE: escape(plugin.source),
          PLUGIN_SKILL_COUNT_PHRASE: plural(plugin.skills.length, 'skill'),
          PLUGIN_MCP_SUMMARY: mcpSummary(plugin.servers),
          SKILL_CARDS: plugin.skills.map(skill => skillCard(skill, plugin, repoUrl)).join('\n'),
          BREADCRUMB_JSONLD: breadcrumbJsonLd(catalog, plugin.display, siteUrl)
        },
        `site/plugin.html (${plugin.name})`
      )
      return writePage(`${plugin.name}/index.html`, html, siteUrl)
    })
  )

  // The server's own page. Its tools come from the table the owning plugin's skills keep;
  // with none found the page would claim capabilities it cannot name, so the build stops.
  if (mcpServer && mcpServer.tools.length === 0) {
    throw new Error(
      `no tool table for '${mcpServer.name}' under ${mcpOwner.source}/skills/. ` +
        `Expected a '## MCP Tool: ${mcpServer.name}' heading followed by a | Tool | Purpose | table.`
    )
  }

  const mcpLabel = `${mcpServer?.name ?? ''} MCP`
  const mcpDescription =
    `${mcpServer?.name} is the MCP server MSU builder skills call for MapleStory Universe ` +
    'resources — name search, then sprite, map, skill, and item data from the MSU Open API.'

  const mcpHtml = render(
    await readFile(join(SITE, 'mcp.html'), 'utf8'),
    partials,
    {
      ...common,
      ...mcpTokens,
      ROOT: '../',
      PAGE_TITLE: escape(`${mcpLabel} — ${MCP_PAGE_IDENTITY}`),
      PAGE_DESCRIPTION: escape(mcpDescription),
      PAGE_URL: `${siteUrl}${MCP_PAGE_DIR}/`,
      MCP_PAGE_LABEL: escape(mcpLabel),
      MCP_PAGE_IDENTITY: escape(MCP_PAGE_IDENTITY),
      MCP_CREDENTIAL_NOTE: escape(mcpServer?.credentialNote ?? ''),
      MCP_TOOL_COUNT_PHRASE: plural(mcpServer?.tools.length ?? 0, 'tool'),
      MCP_TOOL_CARDS: (mcpServer?.tools ?? []).map(toolCard).join('\n'),
      MCP_SKILL_COUNT_PHRASE: plural(mcpSkills.length, 'skill'),
      MCP_SKILL_CARDS: mcpSkills.map(entry => mcpSkillCard(entry, '../')).join('\n'),
      BREADCRUMB_JSONLD: breadcrumbJsonLd(catalog, mcpLabel, siteUrl)
    },
    'site/mcp.html'
  )
  const mcpUrl = await writePage(`${MCP_PAGE_DIR}/index.html`, mcpHtml, siteUrl)

  const pageUrls = [indexUrl, ...pluginUrls, mcpUrl]
  await writeOutput('sitemap.xml', sitemapXml(pageUrls))
  await writeOutput(
    'llms.txt',
    llmsTxt({
      catalog,
      plugins,
      mcpPage: { label: mcpLabel, url: mcpUrl, description: mcpDescription },
      siteUrl,
      repoUrl
    })
  )

  const assets = await copyAssets()

  process.stdout.write(
    `${basename(OUT)}/ — ${pageUrls.length} page(s), ` +
      `${plugins.length} plugin(s), ${skillCount} skill(s), ${assets.length} asset(s), ` +
      'sitemap.xml, llms.txt\n'
  )
}

const run = async () => {
  if (cleanOnly) {
    const removed = await cleanOutputDir()
    process.stdout.write(removed ? `removed ${OUT}\n` : `${OUT} does not exist\n`)
    return
  }
  await build()
}

run().catch(error => {
  process.stderr.write(`build-site: ${error.message}\n`)
  process.exit(1)
})
