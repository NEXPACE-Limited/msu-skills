#!/usr/bin/env node
// Renders the site from the repository itself: the catalog, every plugin manifest, and every
// SKILL.md frontmatter. Nothing about a plugin or a skill is retyped in site/, so adding
// either updates the pages with no edit to this script or to a template.
//
// Output: index.html for the catalog, <plugin>/index.html for each catalogued plugin,
// mcp/index.html for the server a plugin owns, and two machine-readable indexes of those
// same pages — sitemap.xml and llms.txt.
//
// Usage: node scripts/build-site.mjs [outDir]          (default outDir: _site)
//        node scripts/build-site.mjs --clean [outDir]  (remove a marked build only)
// Zero dependencies; Node 18+.

import { readFile, readdir, mkdir, writeFile, copyFile, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join, dirname, basename, resolve, relative, isAbsolute, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SITE = join(ROOT, 'site')
const PARTIALS = join(SITE, 'partials')
const BUILD_MARKER = '.msu-skills-site-build'
const BUILD_MARKER_CONTENT = 'Generated by scripts/build-site.mjs; safe to replace.\n'
// What this site is, in the words every page title ends with. One string, so a plugin page
// and the catalog page cannot describe the site differently.
const SITE_IDENTITY = 'Agent Skills for MapleStory Universe'
// The same role SITE_IDENTITY plays, for the page about the MCP server: one string, so the
// title, the heading, and the llms.txt note cannot describe that server differently.
const MCP_PAGE_IDENTITY = 'MapleStory Universe resource tools'
// Where that page is written. Plugin pages render to /<plugin>/, so a plugin claiming this
// name would collide with it — build() refuses rather than letting one overwrite the other.
const MCP_PAGE_DIR = 'mcp'
// A note in llms.txt is one line in a list, so a description is cut to its first sentence
// and then to this many characters at a word boundary.
const NOTE_LIMIT = 200

const args = process.argv.slice(2)
const cleanOnly = args[0] === '--clean'
const expectedArgs = cleanOnly ? 2 : 1
if (args.length > expectedArgs) {
  throw new Error('usage: node scripts/build-site.mjs [--clean] [outDir]')
}
// resolve, not join: CI passes an absolute path outside the checkout.
const OUT = resolve(ROOT, (cleanOnly ? args[1] : args[0]) ?? '_site')

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }
const escape = value => String(value).replace(/[&<>"']/g, char => ESCAPES[char])

const plural = (count, noun) => (count === 1 ? `one ${noun}` : `${count} ${noun}s`)

/** The first sentence of a description, shortened at a word boundary. An llms.txt note is one
 *  line of a list, while a frontmatter description is written for skill matching and runs
 *  several times longer. */
const shortNote = text => {
  const [sentence] = String(text).trim().split(/(?<=\.)\s+(?=[A-Z])/)
  if (sentence.length <= NOTE_LIMIT) return sentence
  const cut = sentence.slice(0, NOTE_LIMIT)
  return `${cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:—-]$/, '')}…`
}

const readJson = async path => {
  try {
    return JSON.parse(await readFile(path, 'utf8'))
  } catch (error) {
    throw new Error(`cannot read ${path}: ${error.message}`)
  }
}

const listDirs = async path =>
  (await readdir(path, { withFileTypes: true }))
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort()

const userConfigReference = headers =>
  Object.values(headers ?? {})
    .map(value => String(value).match(/^\$\{user_config\.([A-Za-z0-9_-]+)\}$/)?.[1])
    .find(Boolean)

const listFiles = async dir => {
  const entries = await readdir(dir, { withFileTypes: true })
  const nested = await Promise.all(
    entries.map(entry => {
      const path = join(dir, entry.name)
      return entry.isDirectory() ? listFiles(path) : Promise.resolve([path])
    })
  )
  return nested.flat()
}

/** The tools a server exposes, read from the table a skill already keeps for its own agent:
 *  a `## MCP Tool: <server>` heading followed by rows whose first cell is a `code`-quoted
 *  tool name. `.mcp.json` declares how to reach a server, never what it answers, so this
 *  table is the only source — and retyping a tool name into a template would let the page
 *  claim a tool the skills no longer call. */
const parseToolTable = (text, serverName) => {
  const start = text.search(new RegExp(`^##+\\s+MCP Tool:\\s*${serverName}\\s*$`, 'm'))
  if (start === -1) return []

  const [section] = text.slice(start).split(/\n##+\s/)
  return section
    .split('\n')
    .map(line => line.trim())
    .filter(line => line.startsWith('|') && line.endsWith('|'))
    .map(line =>
      line
        .slice(1, -1)
        .split('|')
        .map(cell => cell.trim())
    )
    .filter(cells => cells.length >= 2 && /^`[^`]+`$/.test(cells[0]))
    .map(([name, purpose]) => ({ name: name.slice(1, -1), purpose }))
}

/** One entry per tool name, first mention winning, so a table repeated across references
 *  does not render the same tool twice. */
const uniqueByName = tools => [...new Map(tools.map(tool => [tool.name, tool])).values()]

/** Parses the YAML frontmatter of a SKILL.md. Only flat `key: value` pairs are used, with
 *  wrapped continuation lines folded into the previous value. */
const parseFrontmatter = (text, path) => {
  const lines = text.split('\n')
  if (lines[0]?.trim() !== '---') {
    throw new Error(`${path}: no frontmatter block`)
  }
  const end = lines.findIndex((line, index) => index > 0 && line.trim() === '---')
  if (end === -1) {
    throw new Error(`${path}: frontmatter block is not closed`)
  }

  return lines.slice(1, end).reduce((fields, line) => {
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/)
    if (match) {
      const [, key, raw] = match
      // `description: >` and `description: |` carry the text on the lines below, so the
      // indicator itself is not the value. Both fold to one line here — a card shows the
      // description as a single paragraph either way.
      const value = /^[|>][+-]?\d*$/.test(raw.trim()) ? '' : raw.replace(/^["']|["']$/g, '').trim()
      return { ...fields, [key]: value, _last: key }
    }
    const continued = line.trim()
    if (!continued || !fields._last) return fields
    return { ...fields, [fields._last]: `${fields[fields._last]} ${continued}`.trim() }
  }, {})
}

/** Everything the skill ships besides SKILL.md, at any depth: references/*.md for most,
 *  a library file at the skill root for others. */
const countBundled = async dir => {
  const entries = await readdir(dir, { withFileTypes: true })
  const counts = await Promise.all(
    entries.map(entry => {
      const path = join(dir, entry.name)
      if (entry.isDirectory()) return countBundled(path)
      return Promise.resolve(entry.name === 'SKILL.md' ? 0 : 1)
    })
  )
  return counts.reduce((total, count) => total + count, 0)
}

const readSkill = async (pluginDir, name) => {
  const dir = join(pluginDir, 'skills', name)
  const path = join(dir, 'SKILL.md')
  const fields = parseFrontmatter(await readFile(path, 'utf8'), path)

  if (fields.name !== name) {
    throw new Error(`${path}: frontmatter name '${fields.name}' != directory name '${name}'`)
  }
  if (!fields.description) {
    throw new Error(`${path}: frontmatter has no description`)
  }

  return {
    name,
    description: fields.description,
    bundled: await countBundled(dir),
    // Not every skill has one, and a card must not link to a directory that is not there.
    hasReferences: existsSync(join(dir, 'references'))
  }
}

const readPlugin = async entry => {
  const source = entry.source.replace(/^\.\//, '').replace(/\/$/, '')
  const dir = join(ROOT, source)
  const manifest = await readJson(join(dir, '.claude-plugin', 'plugin.json'))

  const skillsDir = join(dir, 'skills')
  const names = existsSync(skillsDir) ? await listDirs(skillsDir) : []
  const skills = await Promise.all(names.map(name => readSkill(dir, name)))

  // Every markdown file the plugin ships, so a tool table is found wherever its skill keeps
  // it — in SKILL.md or in any reference below it.
  const markdown = existsSync(skillsDir)
    ? (await listFiles(skillsDir)).filter(path => path.endsWith('.md'))
    : []
  const documents = await Promise.all(markdown.map(path => readFile(path, 'utf8')))

  const mcpPath = join(dir, '.mcp.json')
  const declaredServers = existsSync(mcpPath) ? (await readJson(mcpPath)).mcpServers ?? {} : {}
  const servers = Object.entries(declaredServers).map(([name, config]) => {
    const credential = manifest.userConfig?.[userConfigReference(config.headers)]
    return {
      ...config,
      name,
      credentialTitle: credential?.title,
      credentialNote: credential?.description,
      tools: uniqueByName(documents.flatMap(text => parseToolTable(text, name)))
    }
  })

  return {
    name: manifest.name,
    display: manifest.displayName ?? entry.displayName ?? manifest.name,
    description: manifest.description ?? entry.description ?? '',
    version: manifest.version,
    source,
    servers,
    skills
  }
}

const serverList = servers => servers.map(({ name }) => `<code>${escape(name)}</code>`).join(', ')

const TRANSPORTS = { http: 'HTTP / streamable HTTP', sse: 'Server-sent events', stdio: 'stdio' }

const mcpSummary = servers =>
  servers.length === 0
    ? 'None — this plugin needs no credential'
    : `${serverList(servers)} — automatic in Claude Code`

